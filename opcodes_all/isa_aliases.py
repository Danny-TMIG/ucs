def resolve(mnemonic):
    """Return the set of mnemonics that satisfy a semantic query."""
    m = mnemonic.lower()
    if m in ALIASES:
        return set(ALIASES[m]) | {m}
    return {m}


def is_semantic(mnemonic):
    return mnemonic.lower() in ALIASES
